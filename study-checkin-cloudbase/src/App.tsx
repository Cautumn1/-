function studyDate(offset = 0, now = Date.now()) {
  return new Date(now - STUDY_DAY_START_HOUR * HOUR_MS + offset * DAY_MS);
}

function localDay(offset = 0, now = Date.now()) {
  const date = studyDate(offset, now);
  const parts = new Intl.DateTimeFormat("zh-CN", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);
  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

function calendarDay(offset = 0, now = Date.now()) {
  const date = new Date(now + offset * DAY_MS);
  const parts = new Intl.DateTimeFormat("zh-CN", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);
  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

