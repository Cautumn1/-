function parseUnitDirectory(value: string) {
  const entries = value.split(/[\n,，;；]+/).map((item) => item.trim()).filter(Boolean);
  return entries.map((entry) => {
    const numbers = entry.match(/\d+/g)?.map(Number) ?? [];
    if (numbers.length < 2) throw new Error(`无法识别“${entry}”，请按“6:7”填写`);
    return { unit: numbers[0], lessons: numbers[1] };
  });
}

function CourseTemplateEditor({ template, planDays, busy, onBack, onClose, onSave, onDelete }: {
  template: CourseTemplate | null;
  planDays: PlanDay[];
  busy: boolean;
  onBack: () => void;
  onClose: () => void;
  onSave: (input: CourseTemplateInput) => Promise<void>;
  onDelete: (courseId: string, effectiveDay: string) => Promise<void>;
}) {
  const firstPlanDay = planDays[0]?.day ?? localDay();
  const lastPlanDay = planDays[planDays.length - 1]?.day ?? shiftDay(firstPlanDay, 6);
  const today = calendarDay();
  const defaultEffectiveDay = today < firstPlanDay
    ? firstPlanDay
    : today > lastPlanDay ? lastPlanDay : today;
  const [name, setName] = useState(template?.name ?? "");
  const [structure, setStructure] = useState<"unit" | "sequence">(template?.structure ?? "unit");
  const [unitsText, setUnitsText] = useState(template?.units.map((unit) => `${unit.unit}:${unit.lessons}`).join("\n") ?? "");
  const [nextUnit, setNextUnit] = useState(String(template?.nextUnit ?? template?.units[0]?.unit ?? 1));
  const [nextLesson, setNextLesson] = useState(String(template?.nextLesson ?? 1));
  const [totalLessons, setTotalLessons] = useState(template?.totalLessons ? String(template.totalLessons) : "");
  const [weeklyCounts, setWeeklyCounts] = useState<string[]>(template ? template.weeklyCounts.map(String) : Array(7).fill(""));
  const [effectiveDay, setEffectiveDay] = useState(defaultEffectiveDay);
  const [autoContinue, setAutoContinue] = useState(template?.autoContinue ?? true);
  const [message, setMessage] = useState("");
  const [submitting, setSubmitting] = useState(false);

  function changeEffectiveDay(day: string) {
    setEffectiveDay(day);
    if (!template) return;
    const nextTask = planDays
      .filter((entry) => entry.day >= day)
      .flatMap((entry) => entry.tasks)
      .find((task) => task.kind === "course" && task.courseId === template.courseId);
    if (!nextTask) return;
    if (nextTask.unit) setNextUnit(String(nextTask.unit));
    if (nextTask.lesson) setNextLesson(String(nextTask.lesson));
  }

  async function submit() {
    setMessage("");
    try {
      const counts = weeklyCounts.map((value) => Number(value));
      if (counts.some((value) => !Number.isInteger(value) || value < 0 || value > 6)) {
        throw new Error("每天课程数量应填写 0 到 6");
      }
      if (!counts.some((value) => value > 0)) throw new Error("请至少填写一天的课程数量");
      const units = structure === "unit" ? parseUnitDirectory(unitsText) : [];
      if (structure === "unit" && !units.length) throw new Error("请填写课程单元目录");
      const lesson = Number(nextLesson);
      if (!Number.isInteger(lesson) || lesson < 1) throw new Error("请填写正确的下一课");
      setSubmitting(true);
      await onSave({
        courseId: template?.courseId,
        name: name.trim(),
        structure,
        units,
        totalLessons: totalLessons ? Number(totalLessons) : null,
        nextUnit: structure === "unit" ? Number(nextUnit) : null,
        nextLesson: lesson,
        weeklyCounts: counts,
        effectiveDay,
        autoContinue,
      });
    } catch (err) {
      setMessage(err instanceof Error ? err.message : "保存失败");
      setSubmitting(false);
    }
  }

  async function remove() {
    if (!template || !window.confirm(`从 ${formatPlanDate(effectiveDay)} 起停用“${template.name}”吗？\n已完成和此前日期不会改变。`)) return;
    setSubmitting(true);
    setMessage("");
    try { await onDelete(template.courseId, effectiveDay); }
    catch (err) {
      setMessage(err instanceof Error ? err.message : "停用失败");
      setSubmitting(false);
    }
  }

  return (
    <div className="modal-backdrop planner-backdrop">
      <section className="login-card course-template-editor" role="dialog" aria-modal="true" aria-label="编辑课程模板">
        <div className="editor-heading">
          <div><span>COURSE TEMPLATE</span><h2>{template ? "编辑课程模板" : "新建课程模板"}</h2></div>
          <button onClick={onClose} aria-label="关闭">×</button>
        </div>
        <button className="planner-back-button" onClick={onBack}>‹ 返回课程列表</button>
        <div className="course-form">
          <label><span>课程名称</span><input value={name} maxLength={20} placeholder="例如：英语单词" onChange={(event) => setName(event.target.value)} /></label>
          <label><span>课程结构</span><select value={structure} onChange={(event) => setStructure(event.target.value as "unit" | "sequence")}><option value="unit">单元＋课次</option><option value="sequence">单纯连续课次</option></select></label>
          {structure === "unit" ? (
            <>
              <label className="course-directory-field"><span>各单元课数</span><textarea value={unitsText} rows={4} placeholder={"每行一个，例如：\n6:7\n7:5"} onChange={(event) => setUnitsText(event.target.value)} /><small>格式为“单元:课数”，也支持用逗号分隔。</small></label>
              <div className="course-inline-fields">
                <label><span>起始单元</span><input type="number" min="1" inputMode="numeric" value={nextUnit} onChange={(event) => setNextUnit(event.target.value)} /></label>
                <label><span>起始课次</span><input type="number" min="1" inputMode="numeric" value={nextLesson} onChange={(event) => setNextLesson(event.target.value)} /></label>
              </div>
              <small className="course-inline-help">例如填写 6 和 4，第一项自动任务就是“第6单元第4课”。</small>
            </>
          ) : (
            <div className="course-inline-fields">
              <label><span>起始课次</span><input type="number" min="1" inputMode="numeric" value={nextLesson} onChange={(event) => setNextLesson(event.target.value)} /></label>
              <label><span>总课数（可不填）</span><input type="number" min="1" inputMode="numeric" value={totalLessons} onChange={(event) => setTotalLessons(event.target.value)} /></label>
            </div>
          )}

          <fieldset className="weekly-course-fields"><legend>每周学习节奏</legend><div>{WEEKDAY_NAMES.map((weekday, index) => (
            <label key={weekday}><span>{weekday}</span><input type="number" min="0" max="6" inputMode="numeric" value={weeklyCounts[index]} onChange={(event) => setWeeklyCounts((current) => current.map((value, itemIndex) => itemIndex === index ? event.target.value : value))} /><small>课</small></label>
          ))}</div></fieldset>

          <label><span>生效日期</span><input type="date" min={defaultEffectiveDay} max={lastPlanDay} value={effectiveDay} onChange={(event) => changeEffectiveDay(event.target.value)} /><small>默认是北京时间今天，只能选择当前7天窗口内的日期。</small></label>
          <button type="button" className={`repeat-task-toggle ${autoContinue ? "active" : ""}`} role="switch" aria-checked={autoContinue} onClick={() => setAutoContinue((current) => !current)}>
            <span><strong>自动续排未来7天</strong><small>{autoContinue ? "每天打开时自然滚动，不额外写入数据库" : "关闭后由你点击“一键生成未来7天”"}</small></span><i aria-hidden="true"><b /></i>
          </button>
        </div>
        {message && <p className="form-error">{message}</p>}
        <div className={`editor-actions ${template ? "with-delete" : ""}`}>
          {template && <button className="danger-button" onClick={remove} disabled={busy || submitting}>停用课程</button>}
          <button className="secondary-button" onClick={onBack} disabled={busy || submitting}>取消</button>
          <button className="primary-button" onClick={submit} disabled={busy || submitting}>{submitting ? "保存中…" : "保存课程模板"}</button>
        </div>
      </section>
    </div>
  );
}

function TaskEditor({ member, day, tasks, repeatDaily: initialRepeatDaily, showRepeat, onClose, onSave, onReset }: {
  member: Member;
  day: string;
  tasks: StudyTask[];
  repeatDaily: boolean;
  showRepeat: boolean;
  onClose: () => void;
  onSave: (tasks: StudyTask[], repeatDaily: boolean) => Promise<void>;
  onReset: () => Promise<void>;
}) {
  const [drafts, setDrafts] = useState<DraftTask[]>(tasks.map((task) => ({ ...task, key: task.id })));
  const [repeatDaily, setRepeatDaily] = useState(initialRepeatDaily);
  const [saving, setSaving] = useState(false);
  const [message, setMessage] = useState("");

  function addTask() {
    if (drafts.length >= 12) return;
    setDrafts((current) => [...current, { id: "", title: "", completed: false, key: `draft-${Date.now()}-${current.length}` }]);
  }

  function moveTask(key: string, direction: -1 | 1) {
    setDrafts((current) => {
      const index = current.findIndex((task) => task.key === key);
      const nextIndex = index + direction;
      if (index < 0 || nextIndex < 0 || nextIndex >= current.length) return current;
      const reordered = [...current];
      [reordered[index], reordered[nextIndex]] = [reordered[nextIndex], reordered[index]];
      return reordered;
    });
  }

  async function save() {
    const cleaned = drafts.map(({ key: _key, ...task }) => ({ ...task, title: task.title.trim() })).filter((task) => task.title);
    setSaving(true);
    setMessage("");
    try { await onSave(cleaned, repeatDaily); } catch (err) {
      setMessage(err instanceof Error ? err.message : "保存失败");
      setSaving(false);
    }
  }

  async function reset() {
    setSaving(true);
    setMessage("");
    try { await onReset(); } catch (err) {
      setMessage(err instanceof Error ? err.message : "恢复失败");
      setSaving(false);
    }
  }

  return (
    <div className="modal-backdrop">
      <section className="login-card task-editor" role="dialog" aria-modal="true" aria-label={`编辑${day}任务`}>
        <div className="editor-heading"><div><span>{day === localDay() ? "今日计划" : "单日计划"}</span><h2>编辑{formatPlanDate(day)}的任务</h2></div><button onClick={onClose} aria-label="关闭">×</button></div>
        <p className="login-copy">最多添加 12 项。手动保存后，这一天不会再被自动排课覆盖；修改自动课程标题会按新任务处理。</p>
        <div className="task-editor-list">
          {drafts.map((task, index) => (
            <div key={task.key}>
              <span>{index + 1}</span>
              <input
                value={task.title}
                maxLength={task.kind === "course" ? 60 : 30}
                placeholder="输入学习任务"
                onChange={(event) => setDrafts((current) => current.map((item) => item.key === task.key ? { ...item, title: event.target.value } : item))}
              />
              <div className="task-order-buttons" aria-label={`调整第 ${index + 1} 项顺序`}>
                <button onClick={() => moveTask(task.key, -1)} disabled={saving || index === 0} aria-label={`上移第 ${index + 1} 项`}>↑</button>
                <button onClick={() => moveTask(task.key, 1)} disabled={saving || index === drafts.length - 1} aria-label={`下移第 ${index + 1} 项`}>↓</button>
              </div>
              <button onClick={() => setDrafts((current) => current.filter((item) => item.key !== task.key))} aria-label={`删除第 ${index + 1} 项`}>−</button>
            </div>
          ))}
          {!drafts.length && <p>任务列表为空，点击下方按钮添加。</p>}
        </div>
        <button className="add-task-button" onClick={addTask} disabled={drafts.length >= 12}>＋ 添加一项任务</button>
        {showRepeat && <button
          type="button"
          className={`repeat-task-toggle ${repeatDaily ? "active" : ""}`}
          role="switch"
          aria-checked={repeatDaily}
          onClick={() => setRepeatDaily((current) => !current)}
          disabled={saving}
        >
          <span><strong>每天重复</strong><small>{repeatDaily ? "当前任务将从今天起每天自动沿用" : "关闭时只保存当前学习日"}</small></span>
          <i aria-hidden="true"><b /></i>
        </button>}
        {message && <p className="form-error">{message}</p>}
        <div className="editor-actions">
          <button className="secondary-button" onClick={reset} disabled={saving}>{showRepeat ? repeatDaily ? "停止重复并恢复默认" : member.userKey === "user1" ? "恢复默认任务" : "清空今日任务" : "恢复自动计划"}</button>
          <button className="primary-button" onClick={save} disabled={saving}>{saving ? "保存中…" : showRepeat && repeatDaily ? "保存并每天重复" : day === localDay() ? "保存今日任务" : "保存这一天"}</button>
        </div>
      </section>
    </div>
  );
}
