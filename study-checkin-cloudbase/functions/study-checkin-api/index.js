class PublicError extends Error {}

function success(data) {
  return { ok: true, data };
}

function failure(error) {
  const message = error instanceof PublicError ? error.message : "服务暂时不可用，请稍后再试";
  if (!(error instanceof PublicError)) console.error(error);
  return { ok: false, error: message };
}

function first(result) {
  if (!result || !result.data) return null;
  return Array.isArray(result.data) ? result.data[0] ?? null : result.data;
}

function hash(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function validDay(day) {
  return typeof day === "string" && /^\d{4}-\d{2}-\d{2}$/.test(day);
}

function dayInChina(date) {
  const studyDate = new Date(date.getTime() - STUDY_DAY_START_HOUR * HOUR_MS);
  const parts = new Intl.DateTimeFormat("zh-CN", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(studyDate);
  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

function cleanStoredTasks(tasks) {
  if (!Array.isArray(tasks)) return [];
  return tasks.slice(0, MAX_TASKS_PER_DAY).flatMap((task) => {
    const id = typeof task?.id === "string" ? task.id.trim() : "";
    const titleLimit = task?.kind === "course" ? 60 : 30;
    const title = typeof task?.title === "string" ? task.title.trim().slice(0, titleLimit) : "";
    if (!id || !title) return [];
    if (task.kind !== "course") return [{ id, title }];
    const courseId = typeof task.courseId === "string" ? task.courseId.trim().slice(0, 60) : "";
    const scheduleId = typeof task.scheduleId === "string" ? task.scheduleId.trim().slice(0, 60) : "";
    const lessonKey = typeof task.lessonKey === "string" ? task.lessonKey.trim().slice(0, 40) : "";
    if (!courseId || !scheduleId || !lessonKey) return [{ id, title }];
    const cleaned = {
      id,
      title,
      kind: "course",
      courseId,
      scheduleId,
      courseName: typeof task.courseName === "string" ? task.courseName.trim().slice(0, 20) : "",
      lessonKey,
      lesson: Math.max(1, Number(task.lesson) || 1),
      autoGenerated: task.autoGenerated !== false,
    };
    if (Number.isFinite(Number(task.unit))) cleaned.unit = Math.max(1, Number(task.unit));
    if (validDay(task.makeupFromDay)) cleaned.makeupFromDay = task.makeupFromDay;
    return [cleaned];
  });
}

function cleanTaskInput(tasks, existingTasks = []) {
  if (!Array.isArray(tasks)) throw new PublicError("任务列表格式不正确");
  const existingById = new Map(cleanStoredTasks(existingTasks).map((task) => [task.id, task]));
  const seen = new Set();
  const cleaned = [];
  for (const raw of tasks.slice(0, MAX_TASKS_PER_DAY)) {
    let id = typeof raw?.id === "string" && /^[a-zA-Z0-9_-]{1,40}$/.test(raw.id)
      ? raw.id
      : `custom-${crypto.randomBytes(6).toString("hex")}`;
    const existing = existingById.get(id);
    const title = typeof raw?.title === "string"
      ? raw.title.trim().slice(0, existing?.kind === "course" ? 60 : 30)
      : "";
    if (!title) continue;
    if (existing?.kind === "course" && existing.title !== title) {
      id = `custom-${crypto.randomBytes(6).toString("hex")}`;
    } else if (!existing && id.startsWith("course-")) {
      id = `custom-${crypto.randomBytes(6).toString("hex")}`;
    }
    while (seen.has(id)) id = `custom-${crypto.randomBytes(6).toString("hex")}`;
    seen.add(id);
    cleaned.push(existing?.kind === "course" && existing.title === title
      ? { ...existing, title }
      : { id, title });
  }
  return cleaned;
}

function taskTemplateFor(member) {
  if (Array.isArray(member.taskTemplate)) return cleanStoredTasks(member.taskTemplate);
  if (Array.isArray(member.recurringTasks)) return cleanStoredTasks(member.recurringTasks);
  return cleanStoredTasks(DEFAULT_TASKS[member.userKey] ?? []);
}

function baseTasksFor(member, day) {
  if (member.taskOverrides && Object.prototype.hasOwnProperty.call(member.taskOverrides, day)) {
    return cleanStoredTasks(member.taskOverrides[day]);
  }
  const templateSince = typeof member.taskTemplateSince === "string" ? member.taskTemplateSince : "";
  if (Array.isArray(member.taskTemplate) && (!templateSince || day >= templateSince)) {
    return cleanStoredTasks(member.taskTemplate);
  }
  const recurringSince = typeof member.recurringTasksSince === "string" ? member.recurringTasksSince : "";
  if (Array.isArray(member.recurringTasks) && (!recurringSince || day >= recurringSince)) {
    return cleanStoredTasks(member.recurringTasks);
  }
  return DEFAULT_TASKS[member.userKey] ?? [];
}

function tasksFor(member, day) {
  const manuallyOverridden = Boolean(
    member.taskOverrides && Object.prototype.hasOwnProperty.call(member.taskOverrides, day),
  );
  const scheduled = manuallyOverridden ? [] : courseTasksForDay(member, day);
  return mergeUniqueTasks(
    baseTasksFor(member, day),
    scheduled,
    makeupTasksForDay(member, day),
  ).slice(0, MAX_TASKS_PER_DAY);
}

function cleanWeeklyCounts(value) {
  if (!Array.isArray(value) || value.length !== 7) {
    throw new PublicError("请分别设置周一到周日的课程数量");
  }
  const counts = value.map((count) => {
    const parsed = Number(count);
    if (!Number.isInteger(parsed) || parsed < 0 || parsed > 6) {
      throw new PublicError("每天的课程数量应为 0 到 6 课");
    }
    return parsed;
  });
  if (!counts.some((count) => count > 0)) throw new PublicError("每周至少安排一课");
  return counts;
}

function cleanUnits(value) {
  if (!Array.isArray(value) || !value.length || value.length > 40) {
    throw new PublicError("请填写 1 到 40 个单元的课数");
  }
  const seen = new Set();
  let total = 0;
  const units = value.map((entry) => {
    const unit = Number(entry?.unit);
    const lessons = Number(entry?.lessons);
    if (!Number.isInteger(unit) || unit < 1 || unit > 999 || seen.has(unit)) {
      throw new PublicError("单元编号应为不重复的正整数");
    }
    if (!Number.isInteger(lessons) || lessons < 1 || lessons > 200) {
      throw new PublicError("每个单元应包含 1 到 200 课");
    }
    seen.add(unit);
    total += lessons;
    return { unit, lessons };
  });
  if (total > 2000) throw new PublicError("一门课程最多录入 2000 课");
  return units;
}

function unitStartIndex(units, nextUnit, nextLesson) {
  let offset = 0;
  for (const unit of units) {
    if (unit.unit === nextUnit) {
      if (!Number.isInteger(nextLesson) || nextLesson < 1 || nextLesson > unit.lessons) {
        throw new PublicError("下一课不在该单元的课程范围内");
      }
      return offset + nextLesson - 1;
    }
    offset += unit.lessons;
  }
  throw new PublicError("下一课所在单元不在课程目录中");
}

function cleanCourseScheduleInput(event, courseId, scheduleId) {
  const name = typeof event.name === "string" ? event.name.trim().slice(0, 20) : "";
  if (!name) throw new PublicError("请填写课程名称");
  const structure = event.structure === "unit" ? "unit" : event.structure === "sequence" ? "sequence" : "";
  if (!structure) throw new PublicError("请选择课程结构");
  const weeklyCounts = cleanWeeklyCounts(event.weeklyCounts);
  const startDay = event.effectiveDay;
  if (!validDay(startDay)) throw new PublicError("生效日期格式错误");

  const schedule = {
    id: scheduleId,
    courseId,
    name,
    structure,
    weeklyCounts,
    startDay,
    autoContinue: event.autoContinue !== false,
    createdAt: Date.now(),
  };

  if (structure === "unit") {
    const units = cleanUnits(event.units);
    const nextUnit = Number(event.nextUnit);
    const nextLesson = Number(event.nextLesson);
    schedule.units = units;
    schedule.startIndex = unitStartIndex(units, nextUnit, nextLesson);
  } else {
    const nextLesson = Number(event.nextLesson);
    const totalValue = event.totalLessons === "" || event.totalLessons === null || event.totalLessons === undefined
      ? null
      : Number(event.totalLessons);
    if (!Number.isInteger(nextLesson) || nextLesson < 1 || nextLesson > 100000) {
      throw new PublicError("下一课应为正整数");
    }
    if (totalValue !== null && (!Number.isInteger(totalValue) || totalValue < nextLesson || totalValue > 100000)) {
      throw new PublicError("总课数不能小于下一课");
    }
    schedule.totalLessons = totalValue;
    schedule.startIndex = nextLesson - 1;
  }
  return schedule;
}

function currentCourseSchedules(member, day) {
  const schedules = Array.isArray(member.courseSchedules) ? member.courseSchedules : [];
  const candidates = schedules
    .filter((schedule) => !schedule.endDay || schedule.endDay >= day)
    .sort((a, b) => String(b.startDay).localeCompare(String(a.startDay)));
  const seen = new Set();
  return candidates.filter((schedule) => {
    if (!schedule?.courseId || seen.has(schedule.courseId)) return false;
    seen.add(schedule.courseId);
    return true;
  }).sort((a, b) => String(a.name).localeCompare(String(b.name), "zh-CN"));
}

function firstUpcomingCourseTask(schedule, day, actions) {
  let cursor = day < schedule.startDay ? schedule.startDay : day;
  for (let index = 0; index < 21; index += 1) {
    if (schedule.endDay && cursor > schedule.endDay) return null;
    const task = tasksForScheduleDay(schedule, cursor, actions)[0];
    if (task) return task;
    cursor = dateOffset(cursor, 1);
  }
  return null;
}

function publicCourseTemplates(member, day) {
  const actions = Array.isArray(member.courseActions) ? member.courseActions : [];
  return currentCourseSchedules(member, day).map((schedule) => {
    const nextTask = firstUpcomingCourseTask(schedule, day, actions) || (() => {
      const lesson = lessonAt(schedule, 0);
      return lesson ? { unit: lesson.unit, lesson: lesson.lesson, title: `${schedule.name}｜${lesson.label}` } : null;
    })();
    return {
      courseId: schedule.courseId,
      scheduleId: schedule.id,
      name: schedule.name,
      structure: schedule.structure,
      units: schedule.structure === "unit" ? schedule.units : [],
      totalLessons: schedule.structure === "sequence" ? schedule.totalLessons ?? null : null,
      nextUnit: nextTask?.unit ?? null,
      nextLesson: nextTask?.lesson ?? null,
      nextLabel: nextTask?.title ?? "课程已完成",
      weeklyCounts: schedule.weeklyCounts,
      effectiveDay: schedule.startDay,
      autoContinue: schedule.autoContinue !== false,
    };
  });
}

function fullTaskCount(member, day) {
  const manuallyOverridden = Boolean(
    member.taskOverrides && Object.prototype.hasOwnProperty.call(member.taskOverrides, day),
  );
  return mergeUniqueTasks(
    baseTasksFor(member, day),
    manuallyOverridden ? [] : courseTasksForDay(member, day),
    makeupTasksForDay(member, day),
  ).length;
}

function assertCourseCapacity(member, startDay) {
  for (const day of fixedPlanDays(startDay)) {
    if (fullTaskCount(member, day) > MAX_TASKS_PER_DAY) {
      throw new PublicError(`${day} 的总任务会超过 ${MAX_TASKS_PER_DAY} 项，请减少当天课程数量`);
    }
  }
}

