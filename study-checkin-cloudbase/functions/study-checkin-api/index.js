async function saveCourseTemplate(event) {
  requirePlanningWindow(event);
  const member = await readCurrentMember(event.token);
  const existingSchedules = Array.isArray(member.courseSchedules) ? member.courseSchedules : [];
  const requestedCourseId = typeof event.courseId === "string" ? event.courseId : "";
  const existingCourse = requestedCourseId
    ? existingSchedules.some((schedule) => schedule.courseId === requestedCourseId)
    : false;
  if (requestedCourseId && !existingCourse) throw new PublicError("课程模板已不存在，请刷新后重试");

  const activeCourseIds = new Set(currentCourseSchedules(member, event.day).map((schedule) => schedule.courseId));
  if (!existingCourse && activeCourseIds.size >= MAX_COURSES) {
    throw new PublicError(`每人最多设置 ${MAX_COURSES} 门自动课程`);
  }
  if (member.taskOverrides && Object.prototype.hasOwnProperty.call(member.taskOverrides, event.effectiveDay)) {
    throw new PublicError("该日期已手动修改任务，请选择另一个生效日期");
  }

  const courseId = existingCourse ? requestedCourseId : `course-${crypto.randomBytes(8).toString("hex")}`;
  if (existingCourse && event.effectiveDay === event.day) {
    await assertCourseDayMutable(member, courseId, event.effectiveDay);
  }
  const scheduleId = `schedule-${crypto.randomBytes(8).toString("hex")}`;
  const schedule = cleanCourseScheduleInput(event, courseId, scheduleId);
  const previousDay = dateOffset(event.effectiveDay, -1);
  const nextSchedules = existingSchedules.flatMap((item) => {
    if (item.courseId !== courseId) return [item];
    if (item.startDay >= event.effectiveDay) return [];
    if (!item.endDay || item.endDay >= event.effectiveDay) return [{ ...item, endDay: previousDay }];
    return [item];
  });
  nextSchedules.push(schedule);
  const candidate = { ...member, courseSchedules: nextSchedules };
  assertCourseCapacity(candidate, event.day);

  await db.collection("members").doc(member.id).update({
    courseSchedules: nextSchedules,
    updatedAt: Date.now(),
  });
  await markFocusSummaryChanged();
  return { courseId, scheduleId, planDays: fixedPlanDays(event.day) };
}

